// Global setup for the host-integration + offline suite (SP-host): build two tool variants with
// their real deploy headers and start the harness servers (ADR-0010/0011). One variant is built with
// the stub host origin allow-listed (HOST_ORIGINS=HOST_ALLOWED); the other with an empty list, which
// must refuse all embedding and run standalone only (RULE-16, NFR-09). Servers are closed in the
// teardown. Nothing here mutates the repo's `public/_headers` (the per-variant `_headers` is written
// into each dist output only), so `pnpm gen:check` stays clean.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
// @ts-expect-error -- plain ESM build script without type declarations
import { pageCsp, PERMISSIONS_POLICY, SW_CSP } from '../../../scripts/gen-headers.mjs';
// @ts-expect-error -- plain ESM harness module without type declarations
import { staticServer, hostServer } from './server.mjs';
import { HOST_ALLOWED, HOST_OTHER, PORTS } from './urls';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const DIST_ALLOWED = path.join(ROOT, 'dist-e2e', 'allowed');
const DIST_EMPTY = path.join(ROOT, 'dist-e2e', 'empty');
const DIST_ALLOWED_V2 = path.join(ROOT, 'dist-e2e', 'allowed-v2');
const DIST_REVOKED = path.join(ROOT, 'dist-e2e', 'allowed-revoked');

function headersFile(origins: string[]): string {
  // Mirrors scripts/gen-headers.mjs genHeaders(), with frame-ancestors / allow-list from `origins`.
  return `# e2e harness headers (generated by global-setup)
/*
  Content-Security-Policy: ${pageCsp(origins)}
  Permissions-Policy: ${PERMISSIONS_POLICY}
  Referrer-Policy: no-referrer
  X-Content-Type-Options: nosniff
  Cross-Origin-Opener-Policy: same-origin
  Cache-Control: no-cache
/assets/*
  ! Cache-Control
  Cache-Control: public, max-age=31536000, immutable
/sw.js
  ! Content-Security-Policy
  ! Cache-Control
  Content-Security-Policy: ${SW_CSP}
  Cache-Control: no-cache
`;
}

function buildVariant(outDir: string, hostOrigins: string, origins: string[]): void {
  fs.rmSync(outDir, { recursive: true, force: true });
  execFileSync('pnpm', ['exec', 'vite', 'build', '--outDir', outDir, '--emptyOutDir'], {
    cwd: ROOT,
    stdio: 'inherit',
    env: { ...process.env, HOST_ORIGINS: hostOrigins },
  });
  fs.writeFileSync(path.join(outDir, '_headers'), headersFile(origins));
}

/**
 * A newly published version of the allowed build (F-017.AC3): the same build with a new hashed
 * stylesheet (a different name, as a real change gives), a version marker in the page, and a changed
 * /sw.js (so a new worker installs) that answers an `e2e-version` message with 2.
 */
function publishVersion2(from: string, to: string): void {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
  const html = path.join(to, 'index.html');
  let page = fs.readFileSync(html, 'utf8');
  const css = /\/assets\/(index-[\w-]+)\.css/.exec(page);
  if (!css) throw new Error('global-setup: no stylesheet in index.html');
  const renamed = `${css[1]}v2.css`;
  fs.writeFileSync(
    path.join(to, 'assets', renamed),
    fs.readFileSync(path.join(to, 'assets', `${css[1]}.css`), 'utf8') + '\n/* e2e version 2 */\n',
  );
  fs.rmSync(path.join(to, 'assets', `${css[1]}.css`));
  page = page
    .replaceAll(`${css[1]}.css`, renamed)
    .replace('</head>', '<meta name="tk-e2e-version" content="2" /></head>');
  fs.writeFileSync(html, page);
  const sw = path.join(to, 'sw.js');
  fs.writeFileSync(
    sw,
    fs.readFileSync(sw, 'utf8') +
      "\n;self.addEventListener('message', (e) => { if (e.data === 'e2e-version') e.ports[0]?.postMessage(2); });\n",
  );
}

/**
 * The allowed build after the stub host was removed from HOST_ORIGINS (NFR-09, F-017 security m1): the
 * same files, with frame-ancestors naming only the other host.
 */
function revokeHost(from: string, to: string): void {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
  fs.writeFileSync(path.join(to, '_headers'), headersFile([HOST_OTHER]));
}

async function globalSetup(): Promise<void> {
  buildVariant(DIST_ALLOWED, HOST_ALLOWED, [HOST_ALLOWED]);
  buildVariant(DIST_EMPTY, '', []);
  publishVersion2(DIST_ALLOWED, DIST_ALLOWED_V2);
  revokeHost(DIST_ALLOWED, DIST_REVOKED);

  const servers = await Promise.all([
    staticServer({
      root: DIST_ALLOWED,
      port: PORTS.toolAllowed,
      versions: { 2: DIST_ALLOWED_V2, revoked: DIST_REVOKED },
    }),
    staticServer({ root: DIST_EMPTY, port: PORTS.toolEmpty }),
    hostServer({ port: PORTS.hostAllowed }),
    hostServer({ port: PORTS.hostOther }),
  ]);
  (globalThis as unknown as { __harnessServers?: unknown[] }).__harnessServers = servers;
}

export default globalSetup;
